'use strict';
require('./fixtures/sql-native-dns.cjs');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { MongoClient } = require('mongodb');
const { startTestServer, createE2eTargetRegistry } = require('./e2e-harness');
const targets = createE2eTargetRegistry({destructive:true,prefix:'codedb_mongosh_ui'});
const db = targets.target('eventi');
let server, browser, mongo;
(async()=>{
  mongo = new MongoClient('mongodb://127.0.0.1:27039'); await mongo.connect();
  await mongo.db(db).collection('eventi').insertOne({_id:1});
  server = await startTestServer({port:3197,env:{NODE_OPTIONS:'--require=./test/fixtures/sql-native-dns.cjs'}});
  browser = await chromium.launch();
  const page = await browser.newPage({viewport:{width:1440,height:980}}), errors=[];
  if(process.argv.includes('--mutant=formattatore')) await page.route('**/js/query-formatter.js',async route=>{
    const response=await route.fetch(), source=await response.text();
    const from="if (dbms === 'mongosh') return reindentJs(testo);";
    assert(source.includes(from));
    await route.fulfill({response,body:source.replace(from,'')});
  });
  page.on('pageerror',err=>errors.push(err.message));
  await page.addInitScript(version=>localStorage.setItem('codedb:onboarding',JSON.stringify({visto:true,versioneVista:version,traguardi:{},checklistChiusa:true})),require('../package.json').version);
  await page.goto(server.url,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('html[data-arc-ready="true"]');
  await page.evaluate(async db=>{
    const {socket} = await import('/js/socket.js');
    const r = await new Promise(resolve=>socket.emit('mongo:connect',{tabId:'mongo',dbType:'mongodb',host:'127.0.0.1',port:27039},resolve));
    if(!r.ok) throw new Error(r.error);
    const {tabs,createTab} = await import('/js/tabs.js');
    const tab=createTab({id:'mongo'}); tab.dbType='mongodb'; tab.label='mongosh E2E';
    Object.assign(tab.state,{dbType:'mongodb',connected:true,databases:r.databases,collTabs:[]});
    tabs.activeId=tab.id;
    (await import('/js/tabbar.js')).renderTabBar();
    (await import('/js/workspace.js')).renderWorkspace();
    (await import('/js/colltabs.js')).openDbTab(db);
  },db);
  await page.locator('#query-target-btn').click();
  await page.getByRole('combobox',{name:'Motore di esecuzione',exact:true}).click();
  await page.getByRole('option',{name:'mongosh nativo (amministratore)',exact:true}).click();
  await page.locator('#query-target-btn').click();
  const run=async code=>{
    await page.locator('#query-editor-input').fill(code);
    await page.locator('#query-run-btn').click();
    await page.waitForFunction(()=>['success','error'].includes(document.querySelector('#view-query')?.dataset.queryState),null,{timeout:20000});
    assert.equal(await page.locator('#view-query').getAttribute('data-query-state'),'success',await page.locator('#view-query').textContent());
    return page.evaluate(async()=> (await import('/js/query-document.js')).queryDocument());
  };
  await run('const persistente=41; persistente+1');
  await run('persistente+2');
  await run('const select=7; select');
  await page.locator('#query-editor-input').fill('select');
  await page.locator('#query-format-btn').click();
  assert.equal(await page.locator('#query-editor-input').inputValue(),'select');
  await run('print("output-con-risultato"); select');
  assert((await page.locator('#query-mongosh').textContent()).includes('output-con-risultato'));
  await run('db.eventi.watch([], {fullDocument:"updateLookup",maxAwaitTimeMS:100})');
  await page.locator('#query-mongosh').getByText('Chiudi stream',{exact:true}).waitFor();
  await mongo.db(db).collection('eventi').insertOne({_id:2,etichetta:'evento-visibile'});
  await page.waitForFunction(()=>document.querySelector('#query-mongosh').textContent.includes('evento-visibile'));
  await run('persistente+3');
  await mongo.db(db).collection('eventi').updateOne({_id:2},{$set:{etichetta:'evento-successivo'}});
  await page.waitForFunction(()=>document.querySelector('#query-mongosh').textContent.includes('evento-successivo'));
  await page.locator('#query-mongosh').getByText('Resume token',{exact:true}).waitFor();
  await page.screenshot({path:'test-reports/mongosh-2026-10-15/live-ui.png'});
  await page.locator('#query-mongosh').getByText('Chiudi stream',{exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#query-mongosh').textContent.includes('0 stream attivi'));
  await run('config.set("displayBatchSize",1); db.eventi.find().sort({_id:1})');
  assert((await page.locator('#query-mongosh').textContent()).includes('esegui it'));
  await run('it');
  await page.locator('#query-editor-input').fill('print("output-prima-errore"); throw new Error("errore di prova")');
  await page.locator('#query-run-btn').click();
  await page.waitForFunction(()=>document.querySelector('#view-query')?.dataset.queryState==='error');
  assert((await page.locator('#query-mongosh').textContent()).includes('output-prima-errore'));
  await page.locator('#query-mongosh').getByText('Azzera runtime',{exact:true}).click();
  await run('typeof persistente');
  assert((await page.locator('#query-results-container').textContent()).includes('undefined'));
  assert.deepEqual(errors,[]);
  console.log('OK UI reale: selezione mongosh, variabili persistenti, insert/update live fra query, resume token, chiusura e reset');
})().catch(err=>{console.error(err);process.exitCode=1;}).finally(async()=>{
  await browser?.close(); await server?.stop();
  if(mongo){targets.assertOwned(db);await mongo.db(db).dropDatabase();await mongo.close();}
});
