'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { createE2eTargetRegistry } = require('./e2e-harness');
const Strategy = require('../db/PostgreSqlStrategy');
const { runBackup } = require('../backup/lib/engine');
const { runRestore } = require('../backup/lib/restore');
const quiet = { info() {}, error() {} };
(async () => {
  const targets = createE2eTargetRegistry({ destructive:true, prefix:'codedb_part' });
  const source = targets.target('fonte'), target = targets.target('copia');
  targets.assertOwned(source);
  const destRoot = fs.mkdtempSync(path.join(os.tmpdir(),'codedb-part-'));
  const strategy = new Strategy();
  try {
    await strategy.connect({ host:process.env.PGHOST || '127.0.0.1', port:Number(process.env.PGPORT || 5432),
      database:process.env.PGDATABASE || 'postgres', username:process.env.PGUSER || 'postgres', password:process.env.PGPASSWORD || '' });
    const q=(sql,params)=>strategy.pool.query(sql,params);
    const sql = (db, command) => q(command.replaceAll('@', '"'+db+'".'));
    await strategy.createDatabase(source);
    await sql(source, 'CREATE TABLE @z_padre (id integer GENERATED BY DEFAULT AS IDENTITY, zona text, v text) PARTITION BY RANGE(id)');
    await sql(source, 'CREATE TABLE @b_ramo PARTITION OF @z_padre FOR VALUES FROM (0) TO (10) PARTITION BY LIST(zona)');
    await sql(source, "CREATE TABLE @a_foglia PARTITION OF @b_ramo FOR VALUES IN ('nord')");
    await sql(source, 'CREATE TABLE @a_altra PARTITION OF @b_ramo DEFAULT');
    await sql(source, 'CREATE TABLE @a_default PARTITION OF @z_padre DEFAULT');
    await sql(source, 'CREATE INDEX etichetta ON @z_padre (v)');
    await sql(source, "INSERT INTO @z_padre VALUES (1,'nord','uno'),(2,'est','due'),(42,'ovest','tre')");
    await q("SELECT setval(pg_get_serial_sequence($1,'id'), 7, false)",[source+'.z_padre']);
    const session={strategy, dbType:'postgresql'};
    const { autorita, verificaOrigine } = require('../backup/lib/origine');
    const fileConnessioni = path.join(destRoot, 'prova.ini');
    const origine = autorita(fileConnessioni, 'id-sorgente');
    const vault = { loadConnections: () => ({ partizioni: { backupOriginId: origine.id } }), connectionsFileFor: () => fileConnessioni };
    const backup = await runBackup({ session, connName:'partizioni', db:source, type:'full', destRoot, compress:false, log:quiet, origine });
    const utente = collections => require('../auth/principal').makePrincipal({ _id:'sub', ownerId:'azienda', type:'subuser' }, [
      { connName:'partizioni', capabilities:['read'], scope:{ databases:[source], collections } },
    ]);
    assert.throws(() => verificaOrigine(utente(['z_padre']), backup.backupDir, ['z_padre'], destRoot, vault), /Permesso/);
    assert.doesNotThrow(() => verificaOrigine(utente(['*']), backup.backupDir, ['z_padre'], destRoot, vault));
    const data=JSON.parse(fs.readFileSync(path.join(backup.backupDir,'manifest.json'))).files.filter(f=>f.kind==='data');
    assert.equal(data.reduce((n,f)=>n+f.count,0),3,'ogni riga fisica deve comparire una volta nel backup');
    const restore = await runRestore({ session, backupDir:backup.backupDir, targetDb:target, drop:true, log:quiet });
    assert.equal(restore.totalDocs,3);
    const tree=await q("SELECT level,isleaf FROM pg_partition_tree($1::regclass) ORDER BY level,isleaf",[target+'.z_padre']);
    assert.deepEqual(tree.rows.map(r=>[r.level,r.isleaf]),[[0,false],[1,false],[1,true],[2,true],[2,true]]);
    await sql(target, "INSERT INTO @z_padre VALUES (3,'nord','instradata')");
    const {rows} = await sql(target, "SELECT v FROM ONLY @a_foglia ORDER BY id");
    assert.deepEqual(rows.map(r=>r.v),['uno','instradata']);
    const idx=await q("SELECT i.indisvalid FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE c.relname='etichetta' AND n.nspname=$1",[target]);
    assert.equal(idx.rows[0].indisvalid,true);
    const destPiano=targets.target('piano');
    const planArgs = {session, backupDir:backup.backupDir,targetDb:destPiano,drop:true,log:quiet,recoveryRoot:path.join(destRoot,'recupero')};
    const { runRestoreViaPlan } = require('../db/backupRestoreAdapter');
    for (let i=0;i<2;i++) {
      const result=await runRestoreViaPlan(planArgs);
      assert.equal(result.status,'completato',JSON.stringify(result));
      assert.equal(result.totalDocs,3);
    }
    const selettivo=targets.target('selettivo');
    const r=await runRestoreViaPlan({...planArgs,targetDb:selettivo,onlyCollections:['a_foglia']});
    assert.equal(r.status,'completato',JSON.stringify(r));assert.equal(r.totalDocs,1);
    const ident=await sql(selettivo,"INSERT INTO @a_foglia(zona,v) VALUES ('nord','nuovo') RETURNING id");assert.equal(ident.rows[0].id,7);
    const parent=targets.target('albero');
    const albero=await runRestoreViaPlan({...planArgs,targetDb:parent,onlyCollections:['z_padre']});
    assert.equal(albero.status,'completato',JSON.stringify(albero));assert.equal(albero.totalDocs,3);
    // Una selezione del padre possiede anche le foglie già rimosse dal catalogo.
    await sql(source, 'CREATE TABLE @fuori (id INT)');
    const parziale = {session,connName:'solo-padre',db:source,destRoot,compress:false,log:quiet,onlyCollections:['z_padre']};
    const man = r=>JSON.parse(fs.readFileSync(path.join(r.backupDir,'manifest.json')));
    const base = await runBackup({...parziale,type:'full'});
    assert.deepEqual(man(base).entityInventory.selection,['a_altra','a_default','a_foglia','b_ramo','z_padre']);
    await sql(source,'DROP TABLE @a_foglia');
    const rimossa=await runBackup({...parziale,type:'incremental'});
    assert.deepEqual(man(rimossa).entityInventory.removed,['a_foglia']);
    const ridotta=targets.target('ridotta');
    const dopoDrop=await runRestoreViaPlan({...planArgs,backupDir:rimossa.backupDir,targetDb:ridotta,onlyCollections:['z_padre']});
    assert.equal(dopoDrop.status,'completato',JSON.stringify(dopoDrop));
    assert.deepEqual((await sql(ridotta,'SELECT id FROM @z_padre ORDER BY id')).rows.map(row=>row.id),[2,42]);
    assert.equal((await q('SELECT to_regclass($1)::text AS nome',[ridotta+'.a_foglia'])).rows[0].nome,null);

    await sql(source,"CREATE TABLE @a_foglia PARTITION OF @b_ramo (CONSTRAINT controlla CHECK (v <> 'bloccato')) FOR VALUES IN ('sud')");
    await sql(source,"INSERT INTO @z_padre VALUES (4,'sud','nuova generazione')");
    const nuova=await runBackup({...parziale,type:'incremental'});
    const ricreata=targets.target('ricreata');
    const dopoCreate=await runRestoreViaPlan({...planArgs,backupDir:nuova.backupDir,targetDb:ricreata,onlyCollections:['z_padre']});
    assert.equal(dopoCreate.status,'completato',JSON.stringify(dopoCreate));
    assert.deepEqual((await sql(ricreata,'SELECT id FROM @z_padre ORDER BY id')).rows.map(row=>row.id),[2,4,42]);
    assert.deepEqual((await sql(ricreata,'SELECT v FROM ONLY @a_foglia')).rows.map(row=>row.v),['nuova generazione']);
    await assert.rejects(sql(ricreata,"INSERT INTO @z_padre VALUES (5,'sud','bloccato')"),e=>e.code==='23514');
    assert.equal((await q('SELECT to_regclass($1)::text AS nome',[ricreata+'.fuori'])).rows[0].nome,null);
    console.log('Backup e ripristino PostgreSQL: copia fisica, albero, routing e indice partizionato verificati.');
  } finally {
    try { if (strategy.pool) await targets.cleanup(name=>strategy.pool.query('DROP SCHEMA IF EXISTS "'+name+'" CASCADE')); }
    finally { await strategy.disconnect(); fs.rmSync(destRoot,{recursive:true,force:true}); }
  }
})().catch(err=>{console.error(err);process.exitCode=1;});
